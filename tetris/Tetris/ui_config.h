// ============================================================
// 六、七种方块的颜色（国际标准配色）
// ------------------------------------------------------------
// 下标与方块编号一一对应：0=I 1=O 2=T 3=S 4=Z 5=J 6=L
// 到 Phase 2 会由 tetromino 模块按编号取用这里的颜色。
// ============================================================
static const Color BLOCK_COLORS[7] =
{
    { 53,  197, 240, 255 },   // 0  I 青  #35C5F0
    { 255, 217, 61,  255 },   // 1  O 黄  #FFD93D
    { 177, 77,  255, 255 },   // 2  T 紫  #B14DFF
    { 61,  220, 90,  255 },   // 3  S 绿  #3DDC5A
    { 255, 77,  77,  255 },   // 4  Z 红  #FF4D4D
    { 77,  107, 254, 255 },   // 5  J 蓝  #4D6BFE
    { 255, 154, 61,  255 }    // 6  L 橙  #FF9A3D
};

// 按方块编号取颜色。编号越界时回退到 0 号（I 青），避免越界读数组。
// 界面层只"取用"编号对应的颜色，不判断任何游戏规则。
static inline Color BlockColorOf(int id)
{
    if (id < 0 || id >= TETROMINO_COUNT)
    {
        id = 0;
    }
    return BLOCK_COLORS[id];
}

