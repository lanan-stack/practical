// ============================================================
// config.h —— 逻辑层全局常量
// ------------------------------------------------------------
// 所属层次：配置（逻辑层与测试工程共用）
//
// 【本文件不包含 raylib】——这一点很重要：逻辑层必须能脱离窗口做单元测试，
// 所以棋盘尺寸、出生位置这类"游戏规则相关"的常量放在这里，
// 而窗口尺寸、配色、像素坐标那些"界面相关"的常量放在 ui_config.h。
//
// 所有数值集中在此，不允许散落在函数里（规格第 7.3 节第 3 条）。
// ============================================================
#ifndef CONFIG_H
#define CONFIG_H

// ============================================================
// 一、棋盘尺寸（方案乙：隐藏缓冲模型）
// ------------------------------------------------------------
// 逻辑棋盘一共 22 行，其中：
//   · 逻辑第 0 ~ 1 行：隐藏缓冲行，**不显示**；
//   · 逻辑第 2 ~ 21 行：屏幕上可见的 20 行。
// 行号换算：屏幕上第 r 行（r = 0 表示最上面一行） = 逻辑第 r + 2 行。
//
// 为什么要缓冲行：方块出生在缓冲行附近，留有旋转与顶出判定的余量，
// 避免"刚出生就被判死"的糟糕体验。
// ============================================================
#define BOARD_COLS         10   // 棋盘列数（横向格数）
#define BOARD_VISIBLE_ROWS 20   // 可见行数（屏幕上真正显示的 20 行）
#define BOARD_BUFFER_ROWS  2    // 顶部隐藏缓冲行数（不显示）

// 逻辑总行数 = 可见行 + 缓冲行 = 22
#define BOARD_TOTAL_ROWS   (BOARD_VISIBLE_ROWS + BOARD_BUFFER_ROWS)

// ============================================================
// 二、方块盒子与出生位置
// ------------------------------------------------------------
// 七种方块统一放在一个 4 × 4 的盒子里表示（详见 tetromino.c 的说明）。
// 出生时，盒子左上角放在逻辑棋盘的 (列 3, 行 1)：
//   · 列 3 让方块水平居中：(10 - 4) / 2 = 3；
//   · 行 1 让每种方块出生时都恰好有一格落在可见区最上面一行（逻辑第 2 行），
//     玩家能立刻看到方块进场，同时逻辑第 0 行留作缓冲。
// ============================================================
#define TETROMINO_BOX      4                                // 盒子边长
#define SPAWN_BOX_COL      ((BOARD_COLS - TETROMINO_BOX) / 2)  // = 3
#define SPAWN_BOX_ROW      1                                // = 1
#define SPAWN_VISIBLE_ROW  BOARD_BUFFER_ROWS                // 可见区最上面一行的逻辑行号 = 2

// ============================================================
// 三、下落与锁定（Phase 5）
// ------------------------------------------------------------
// 本阶段的下落速度先用固定值（等于速度表的第 1 级）；
// 到 Phase 6 接上"等级 / 三档难度"后，这里会变成按当前等级取值。
// ============================================================
#define FALL_INTERVAL_LEVEL1  1.0    // 正常下落间隔（秒/格）
// 【手感调优记录】初版是 10 倍速（每格 0.1 秒），实测偏快、不好精细对齐，
// 经用户确认放慢到 7 倍速（每格约 0.14 秒）。
#define SOFT_DROP_MULTIPLIER  7.0    // 软降：速度变为正常的 7 倍（即间隔变成 1/7）
#define LOCK_DELAY_SECONDS    0.5    // 落地后的锁定延迟（秒）
#define LOCK_RESET_MAX        8      // 锁定延迟最多因"成功的移动/旋转"重置几次

// ============================================================
// 四、按键长按连发（DAS / ARR）
// ------------------------------------------------------------
// DAS（Delayed Auto Shift）：按住方向键后，开始连发前的等待时间。
// ARR（Auto Repeat Rate）：进入连发后，每次移动之间的间隔。
// 这两个数值共同决定"按住左键时方块滑得快不快"，是手感的两个关键参数。
// ============================================================
// 【手感调优记录】初版用的是 0.17 / 0.08，实测偏快（每秒 12.5 格，横穿棋盘不到 0.8 秒），
// 与"放松解压"的定位不符，用户确认后放慢到 0.20 / 0.13（每秒约 7.7 格）。
#define INPUT_DAS_SECONDS     0.20   // 连发前的等待（秒）
#define INPUT_ARR_SECONDS     0.13   // 连发间隔（秒）

// ============================================================
// 五、棋盘内容的标记（逻辑层用）
// ------------------------------------------------------------
// 棋盘每格存的是"占据它的方块编号 0~6"，空格用 -1 表示。
// 之所以不用 0 表示空格：0 是 I 形的合法编号（这正是循环队列
// 不能用 0 当哨兵值的同一个道理）。
// ============================================================
#define BOARD_EMPTY  (-1)

// ============================================================
// 六、消行、计分与等级（Phase 6）
// ------------------------------------------------------------
// 计分公式（依据 project.md 第 2.3 节）：
//     本次得分 = 消行基础分 × 消行前的等级 + 连击加成
//     连击加成 = 50 × (连击次数 − 1) × 消行前的等级   （连击次数 ≥ 2 时才有）
// 基础分见 game_logic.c 里的 LINE_CLEAR_POINTS 表：1/2/3/4 行 = 100/300/500/800。
//
// 注意"消行前的等级"：这一手是你用当时的等级完成的，所以按升级之前的等级算分。
// ============================================================
#define CLEAR_FLASH_SECONDS  0.15   // 消行闪烁时长（秒）；闪烁结束后才真正移除该行
#define LINES_PER_LEVEL      10     // 每消多少行升一级
#define COMBO_BONUS_BASE     50     // 连击加成基数

#endif // CONFIG_H
